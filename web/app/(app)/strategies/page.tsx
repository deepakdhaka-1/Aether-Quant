import type { Metadata } from "next";
import { Marketplace } from "@/components/strategies/Marketplace";
import { loadPublished } from "@/components/strategies/data";
import { Card, Empty, ErrorNote, PageTitle } from "@/components/ui";
import { supabaseServer } from "@/lib/supabase/server";

export const metadata: Metadata = { title: "Strategies" };

export default async function StrategiesPage() {
  const sb = await supabaseServer();
  const { data, error } = await loadPublished(sb);
  return (
    <>
      <PageTitle
        title="Strategy marketplace"
        sub="Every strategy is generated by our models, backtested in-sample, then checked out-of-sample before it is published. Past performance does not predict future results."
      />
      {error ? (
        <ErrorNote message={error} />
      ) : data.length ? (
        <Marketplace strategies={data} />
      ) : (
        <Card>
          <Empty title="No published strategies yet">
            New strategies are released after they pass out-of-sample validation. Check back soon.
          </Empty>
        </Card>
      )}
    </>
  );
}
