-- Human-friendly strategy number (1, 2, 3 ...). `id` stays the uuid primary key because
-- backtests, strategy_signals, follows, orders and fills reference it.
alter table strategies add column if not exists strategy_no bigint;

-- Number existing rows in creation order.
update strategies s
set strategy_no = r.n
from (select id, row_number() over (order by created_at, slug) as n from strategies) r
where r.id = s.id and s.strategy_no is null;

alter table strategies alter column strategy_no set not null;
alter table strategies alter column strategy_no add generated by default as identity;
alter table strategies add constraint strategies_strategy_no_key unique (strategy_no);

-- New rows continue after the highest existing number.
select setval(pg_get_serial_sequence('strategies', 'strategy_no'),
              coalesce((select max(strategy_no) from strategies), 0) + 1, false);
