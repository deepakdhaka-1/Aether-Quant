-- profiles: read/update own (role column protected by trigger below); admin reads all
create policy profiles_self_read   on profiles for select using (id = auth.uid() or is_admin());
create policy profiles_self_update on profiles for update using (id = auth.uid()) with check (id = auth.uid());

create or replace function protect_profile_role() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.role is distinct from old.role and not is_admin() and auth.role() <> 'service_role' then
    raise exception 'role can only be changed by an admin';
  end if;
  if new.wallet_address is distinct from old.wallet_address and auth.role() <> 'service_role' then
    raise exception 'wallet_address is set by wallet sign-in only';
  end if;
  return new;
end; $$;
drop trigger if exists profiles_protect_role on profiles;
create trigger profiles_protect_role before update on profiles
  for each row execute function protect_profile_role();

