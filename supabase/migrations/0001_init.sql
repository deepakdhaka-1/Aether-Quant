-- Subscriptions must point at the caller's own broker account and a published strategy
-- they are entitled to by tier.
create or replace function check_subscription() returns trigger
language plpgsql security definer set search_path = public as $$
declare v_owner uuid; v_status text;
begin
  select user_id into v_owner from broker_accounts where id = new.broker_account_id;
  if v_owner is distinct from new.user_id then
    raise exception 'broker account does not belong to this user';
  end if;
  select status into v_status from strategies where id = new.strategy_id;
  if v_status <> 'published' and tg_op = 'INSERT' then
    raise exception 'strategy is not open for subscriptions';
  end if;
  -- Hyperliquid nets positions per coin: two strategies on one coin in one account would fight.
  if exists (
       select 1 from subscriptions x
         join strategies a on a.id = x.strategy_id
         join strategies b on b.id = new.strategy_id
        where x.broker_account_id = new.broker_account_id and x.id <> new.id
          and a.symbol = b.symbol) then
    raise exception 'you already follow a strategy on this market with this account';
  end if;
  if new.mode = 'live' and not exists (
       select 1 from broker_accounts b where b.id = new.broker_account_id
         and b.status = 'active' and b.agent_approved and b.builder_approved) then
    raise exception 'connect and approve your Hyperliquid wallet before going live';
  end if;
  return new;
end; $$;
drop trigger if exists subscriptions_check on subscriptions;
create trigger subscriptions_check before insert or update on subscriptions
  for each row execute function check_subscription();
