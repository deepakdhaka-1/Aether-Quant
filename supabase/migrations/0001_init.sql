create table if not exists exec_lock (
  name        text primary key,
  holder      text not null,
  expires_at  timestamptz not null
);
create or replace function try_exec_lock(p_name text, p_holder text, p_ttl_s int)
returns boolean language plpgsql security definer set search_path = public as $$
begin
  insert into exec_lock (name, holder, expires_at)
  values (p_name, p_holder, now() + make_interval(secs => p_ttl_s))
  on conflict (name) do update
    set holder = excluded.holder, expires_at = excluded.expires_at
    where exec_lock.expires_at < now() or exec_lock.holder = excluded.holder;
  return found;
end; $$;
create or replace function release_exec_lock(p_name text, p_holder text)
returns void language sql security definer set search_path = public as $$
  delete from exec_lock where name = p_name and holder = p_holder;
$$;
revoke execute on function try_exec_lock(text,text,int) from public, anon, authenticated;
revoke execute on function release_exec_lock(text,text) from public, anon, authenticated;

