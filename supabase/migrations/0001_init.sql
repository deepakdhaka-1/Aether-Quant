-- ---------- strategies (published by admin; generated by the offline model) ----------
create table if not exists strategies (
  id               uuid primary key default gen_random_uuid(),
  slug             text unique not null,
  name             text not null,
  description      text,
  symbol           text not null references markets(symbol),
  timeframe        text not null check (timeframe in ('15m','1h','4h','1d')),
  direction        text not null default 'both' check (direction in ('long','short','both')),
  entry_long       text, exit_long text, entry_short text, exit_short text,
  stop_loss_pct    numeric check (stop_loss_pct is null or stop_loss_pct > 0),
  take_profit_pct  numeric check (take_profit_pct is null or take_profit_pct > 0),
  default_leverage numeric not null default 1 check (default_leverage > 0 and default_leverage <= 10),
  risk_level       text not null default 'medium' check (risk_level in ('low','medium','high')),
  status           text not null default 'draft'
                   check (status in ('draft','backtested','published','paused','retired')),
  source           text not null default 'manual' check (source in ('manual','offline_model')),
  model_name       text,
  generation_meta  jsonb not null default '{}',
  headline_metrics jsonb not null default '{}',   -- cached from latest backtest for cards
  created_by       uuid references profiles(id),
  created_at       timestamptz not null default now(),
  published_at     timestamptz
);

create table if not exists backtests (
  id            uuid primary key default gen_random_uuid(),
  strategy_id   uuid not null references strategies(id) on delete cascade,
  period_start  timestamptz, period_end timestamptz,
  metrics       jsonb not null,                 -- return_pct, sharpe, max_dd_pct, win_rate, pf, trades
  equity_curve  jsonb not null default '[]',    -- [[epoch_s, equity], ...] downsampled
  trades        jsonb not null default '[]',
  created_at    timestamptz not null default now()
);
create index if not exists backtests_strategy_idx on backtests (strategy_id, created_at desc);

-- Desired position per strategy per closed bar (written by engine signal runner).
create table if not exists strategy_signals (
  id           bigint generated always as identity primary key,
  strategy_id  uuid not null references strategies(id) on delete cascade,
  bar_time     timestamptz not null,
  desired      text not null check (desired in ('long','short','flat')),
  price        numeric,
  reason       text,
  created_at   timestamptz not null default now(),
  unique (strategy_id, bar_time)
);
create index if not exists strategy_signals_latest_idx on strategy_signals (strategy_id, bar_time desc);

-- ---------- broker accounts ----------
-- agent_secret_enc is NEVER readable by the client (column privilege revoked below).
create table if not exists broker_accounts (
  id                  uuid primary key default gen_random_uuid(),
  user_id             uuid not null references profiles(id) on delete cascade,
  broker              text not null default 'hyperliquid' check (broker in ('hyperliquid')),
  network             text not null default 'mainnet' check (network in ('mainnet','testnet')),
  wallet_address      text not null,            -- user's master wallet (lowercase)
  wallet_provider     text,                     -- metamask / okx / rabby / ...
  agent_address       text not null,            -- server-generated agent wallet
  agent_secret_enc    text not null,            -- AES-256-GCM envelope (see web/lib/crypto.ts)
  agent_approved      boolean not null default false,
  builder_approved    boolean not null default false,
  builder_max_fee     text,                     -- e.g. '0.05%' as approved by the user
  status              text not null default 'pending'
                      check (status in ('pending','active','error','revoked')),
  kill_switch         boolean not null default false,
  last_error          text,
  terms_accepted_at   timestamptz,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  unique (wallet_address, network)              -- one owner per wallet per network
);

-- ---------- subscriptions: user -> strategy on a broker account ----------
create table if not exists subscriptions (
  id                 uuid primary key default gen_random_uuid(),
  user_id            uuid not null references profiles(id) on delete cascade,
  strategy_id        uuid not null references strategies(id) on delete cascade,
  broker_account_id  uuid not null references broker_accounts(id) on delete cascade,
  allocation_pct     numeric not null check (allocation_pct > 0 and allocation_pct <= 1),
  leverage           numeric not null default 1 check (leverage > 0 and leverage <= 10),
  mode               text not null default 'paper' check (mode in ('paper','live')),
  enabled            boolean not null default true,
  created_at         timestamptz not null default now(),
  unique (broker_account_id, strategy_id)
);

