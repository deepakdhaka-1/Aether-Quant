-- ============================================================
-- Aether Quant — multi-user AI strategy platform on Hyperliquid
-- Fresh Supabase project. Additive; safe to re-run (IF NOT EXISTS).
-- Custody model: users keep funds. We hold an AGENT key per user
-- (trade-only, cannot withdraw), generated server-side and approved
-- by the user's own wallet signature (approveAgent). Revenue: every
-- order carries our Hyperliquid builder code (approveBuilderFee).
-- ============================================================

create extension if not exists pgcrypto;

-- ---------- profiles ----------
create table if not exists profiles (
  id             uuid primary key references auth.users(id) on delete cascade,
  email          text,
  username       text unique,
  wallet_address text unique,                 -- EVM address used for wallet sign-in (lowercase)
  role           text not null default 'user' check (role in ('user','admin')),
  referral_code  text,
  created_at     timestamptz not null default now()
);

create or replace function is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from profiles where id = auth.uid() and role = 'admin');
$$;

create or replace function handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into profiles (id, email, username, wallet_address, referral_code)
  values (
    new.id,
    new.email,
    nullif(new.raw_user_meta_data->>'username', ''),
    lower(nullif(new.raw_user_meta_data->>'wallet_address', '')),
    nullif(new.raw_user_meta_data->>'referral_code', '')
  )
  on conflict (id) do nothing;
  return new;
end; $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function handle_new_user();

